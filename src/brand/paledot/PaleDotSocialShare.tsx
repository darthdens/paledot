export function PaleDotSocialShare({ message, label, copiedLabel }: { message: string; label: string; copiedLabel: string }) {
  const [copied, setCopied] = useState(false);

  // Instagram has no web share link: use the phone share sheet, else copy the link and open Instagram.
  const instagram = async () => {
    if (navigator.share) {
      try {
        await navigator.share({ title: "Pale Dot", text: message, url: URL_ });
        return;
      } catch (e) {
        if ((e as Error)?.name === "AbortError") return;
      }
    }
    try {
      await navigator.clipboard.writeText(`${message} ${URL_}`);
      setCopied(true);
      window.setTimeout(() => setCopied(false), 2000);
    } catch {
      /* ignore */
    }
    window.open("https://www.instagram.com/", "_blank", "noopener,noreferrer");
  };

  return (
    <div className="pd-social" role="group" aria-label={label}>
      {NETS.map((n) => {
        const icon = (
          <svg viewBox="0 0 24 24" width="16" height="16" aria-hidden="true" fill="currentColor"><path d={n.path} /></svg>
        );
        const title = `${label} · ${n.label}`;
        return n.href ? (
          <a key={n.id} data-action className="pd-social-btn" href={n.href(URL_, message)} target="_blank" rel="noopener noreferrer" aria-label={title} title={title}>
            {icon}
          </a>
        ) : (
          <button key={n.id} type="button" data-action className="pd-social-btn" onClick={instagram} aria-label={title} title={title}>
            {icon}
          </button>
        );
      })}
      {copied && <span className="pd-social-note" aria-live="polite">{copiedLabel}</span>}
    </div>
  );
}
